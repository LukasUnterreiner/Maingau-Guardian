#!/usr/bin/env node
// Renders lighty-pitch.html into the 40-second pitch video.
//
//   node capture.cjs                        # first: record the real app into demo-frames/ (app must be running)
//   node render.cjs                         # → lighty-pitch-40s.mp4, storyboard.png, timing-report.md
//   node render.cjs --bg "#FFFFFF" --accent "#0069F1" --out other.mp4
//   node render.cjs --stills ./frames       # key frames only, no video (fast check)
//
// Needs Node with Playwright + Chromium, ffmpeg with libx264, and python3 with numpy (for music.py).
"use strict";
const { chromium } = require("playwright");
const http = require("http");
const fs = require("fs");
const path = require("path");
const { spawn, execFileSync } = require("child_process");

const DIR = __dirname;
const FPS = 30;
const DURATION = 40;
const FRAMES = FPS * DURATION;
const DISSOLVES = [8.0, 35.0];   // centres of the 0.5 s scene changes where two scenes overlap
const MAX_WORDS = 8;
const MIN_READ = 3.0;

// Storyboard frames: one per beat.
const KEY_FRAMES = [
  [2.8, "The problem"], [6.5, "Lighty"], [9.6, "Regions: all of Germany"],
  [11.0, "Click: Hessen"], [13.0, "Click: Hanau"], [15.8, "Churn risk page"],
  [18.8, "Click: the customer's row"], [21.2, "Churn card: why"], [25.0, "Lighty's next step"],
  [28.6, "Typing to Ask Lighty"], [33.0, "Lighty's answer"], [38.0, "Closing"],
];

function parseArgs(argv) {
  const a = { out: path.join(DIR, "lighty-pitch-40s.mp4") };
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i].replace(/^--/, "");
    a[k] = argv[i + 1] && !argv[i + 1].startsWith("--") ? argv[++i] : true;
  }
  return a;
}

function serve(root) {
  const types = { ".html": "text/html", ".woff2": "font/woff2", ".wav": "audio/wav", ".png": "image/png",
    ".jpg": "image/jpeg", ".json": "application/json", ".js": "text/javascript" };
  const server = http.createServer((req, res) => {
    const file = path.join(root, decodeURIComponent(new URL(req.url, "http://x").pathname));
    if (!file.startsWith(root) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { res.writeHead(404); return res.end(); }
    res.writeHead(200, { "Content-Type": types[path.extname(file)] || "application/octet-stream" });
    fs.createReadStream(file).pipe(res);
  });
  return new Promise((ok) => server.listen(0, "127.0.0.1", () => ok(server)));
}

const fmt = (t) => `0:${t.toFixed(2).padStart(5, "0")}`;
const inDissolve = (t) => DISSOLVES.some((b) => Math.abs(t - b) < 0.25);

function timingReport(samples, audio, probe, opts) {
  const units = new Map();
  let maxSettled = { words: 0, t: 0, ids: [] };
  let overSettled = 0;
  for (const { t, text } of samples) {
    const visible = text.filter((u) => u.vis > 0.02);
    for (const u of text) {
      if (!units.has(u.id)) units.set(u.id, { text: u.text, words: u.words, frames: [] });
      if (u.vis >= 0.5) { units.get(u.id).frames.push(t); units.get(u.id).text = u.text; }
    }
    if (!inDissolve(t)) {
      const words = visible.reduce((s, u) => s + u.words, 0);
      if (words > maxSettled.words) maxSettled = { words, t, ids: visible.map((u) => u.text) };
      if (words > MAX_WORDS) overSettled++;
    }
  }
  const rows = [...units.values()].filter((u) => u.frames.length).map((u) => {
    const secs = u.frames.length / FPS;
    return `| ${u.text} | ${u.words} | ${fmt(u.frames[0])} | ${fmt(u.frames[u.frames.length - 1] + 1 / FPS)} | ${secs.toFixed(2)} s | ${secs >= MIN_READ ? "yes" : "**no**"} |`;
  });
  const short = [...units.values()].filter((u) => u.frames.length && u.frames.length / FPS < MIN_READ);
  return [
    "# Timing report",
    "",
    "Generated by `render.cjs` from the frames that went into the video. Do not edit by hand.",
    "",
    `* Output: \`${path.basename(opts.out)}\`, ${probe.width}×${probe.height}, ${probe.fps} fps, ${probe.frames} frames, ` +
      `duration ${probe.duration} s (video stream ${probe.vduration} s, audio stream ${probe.aduration} s)`,
    `* Most words visible in a settled frame (outside the 0.5 s dissolves): **${maxSettled.words}** at ${fmt(maxSettled.t)} ` +
      `(${maxSettled.ids.map((s) => `“${s}”`).join(" + ")}); frames over ${MAX_WORDS}: ${overSettled}`,
    `* Lines readable (≥ 50 % opacity) for less than ${MIN_READ} s: ${short.length ? short.map((u) => `“${u.text}”`).join(", ") : "none"}`,
    "",
    "Counted: the titles and captions this video adds. The recorded app screens are not counted. During each 0.5 s " +
      "cross-dissolve the outgoing and incoming text overlap at partial opacity; the word limit is checked on settled frames.",
    "",
    `| Text on screen | Words | Readable from | until | Time | ≥ ${MIN_READ} s |`,
    "|---|---:|---|---|---:|:---:|",
    ...rows,
    "",
    "## Music bed",
    "",
    `Integrated loudness ${audio.lufs} LUFS, true peak ${audio.peak_dbfs} dBTP. Level per section (RMS, dBFS):`,
    "",
    "| Section | RMS |",
    "|---|---:|",
    ...audio.sections.map((s) => `| ${s.name} | ${s.rms_dbfs} |`),
    "",
  ].join("\n");
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  const stillsDir = opts.stills === true ? path.join(DIR, "frames") : opts.stills;
  const wav = path.join(DIR, "music.wav");

  const server = await serve(DIR);
  const q = new URLSearchParams({ render: "1" });
  for (const k of ["bg", "accent"]) if (typeof opts[k] === "string") q.set(k, opts[k]);
  if (!fs.existsSync(path.join(DIR, "demo-frames", "manifest.json"))) throw new Error("no demo-frames/: run capture.cjs first");
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 });
  await page.goto(`http://127.0.0.1:${server.address().port}/lighty-pitch.html?${q}`);
  const fontOk = await page.evaluate(() => window.videoReady);
  if (!fontOk) throw new Error("Plus Jakarta Sans did not load; refusing to render with a fallback font");

  // music bed plus the sound effects at the moments the video names (clicks, key taps, whooshes)
  let audio = null;
  if (!stillsDir) {
    const cues = path.join(DIR, "sound-cues.json");
    fs.writeFileSync(cues, JSON.stringify(await page.evaluate(() => window.soundCues()), null, 1));
    console.log("music: synthesising music.wav with the sound effects");
    audio = JSON.parse(execFileSync("python3", [path.join(DIR, "music.py"), wav, cues], { encoding: "utf8" }));
  }

  const keyIdx = new Map(KEY_FRAMES.map(([t, label]) => [Math.round(t * FPS), label]));
  const stills = [];

  if (stillsDir) {
    fs.mkdirSync(stillsDir, { recursive: true });
    for (const [t, label] of KEY_FRAMES) {
      await page.evaluate(async (s) => { await window.renderAt(s); }, t);
      const file = path.join(stillsDir, `${t.toFixed(1).padStart(4, "0")}s.png`);
      await page.screenshot({ path: file });
      console.log(`${fmt(t)}  ${label}  → ${file}`);
    }
    await browser.close(); server.close();
    return;
  }

  const ff = spawn("ffmpeg", [
    "-y", "-loglevel", "error",
    "-f", "image2pipe", "-framerate", String(FPS), "-c:v", "png", "-i", "-",
    "-i", wav,
    "-map", "0:v", "-map", "1:a",
    "-vf", "scale=out_color_matrix=bt709:out_range=tv,format=yuv420p",
    "-c:v", "libx264", "-preset", "slow", "-crf", "16", "-tune", "animation", "-g", String(FPS * 2),
    "-colorspace", "bt709", "-color_primaries", "bt709", "-color_trc", "bt709", "-color_range", "tv",
    "-c:a", "aac", "-b:a", "192k", "-ar", "48000",
    "-t", String(DURATION), "-movflags", "+faststart", opts.out,
  ], { stdio: ["pipe", "inherit", "inherit"] });
  const done = new Promise((ok, fail) => ff.on("close", (c) => (c === 0 ? ok() : fail(new Error(`ffmpeg exited ${c}`)))));

  const samples = [];
  const started = Date.now();
  for (let i = 0; i < FRAMES; i++) {
    const t = i / FPS;
    const text = await page.evaluate(async (s) => { await window.renderAt(s); return window.measureText(); }, t);
    samples.push({ t, text });
    const png = await page.screenshot({ type: "png" });
    if (keyIdx.has(i)) stills.push([t, keyIdx.get(i), png]);
    if (!ff.stdin.write(png)) await new Promise((ok) => ff.stdin.once("drain", ok));
    if (i % 150 === 0) console.log(`frame ${i}/${FRAMES}  (${((Date.now() - started) / 1000).toFixed(0)} s)`);
  }
  ff.stdin.end();
  await done;

  // storyboard: the key frames on one sheet
  const tiles = stills.map(([t, label, png]) => `
    <figure><img src="data:image/png;base64,${png.toString("base64")}"><figcaption><b>${fmt(t)}</b> ${label}</figcaption></figure>`).join("");
  await page.setViewportSize({ width: 2000, height: 1200 });
  await page.setContent(`<!doctype html><style>
    @font-face { font-family: J; src: url("http://127.0.0.1:${server.address().port}/fonts/PlusJakartaSans-latin-wght.woff2"); font-weight: 200 800; }
    body { margin: 0; padding: 40px; background: #FFFFFF; font: 500 22px J, sans-serif; color: #1B4274; }
    h1 { margin: 0 0 28px; font-size: 34px; font-weight: 750; color: #002657; letter-spacing: -.02em; }
    main { display: grid; grid-template-columns: repeat(4, 1fr); gap: 28px 24px; }
    figure { margin: 0; } img { width: 100%; display: block; border-radius: 10px; border: 1px solid #E2EAF6; }
    figcaption { margin-top: 10px; } b { color: #002657; font-weight: 750; margin-right: 8px; }
  </style><h1>Lighty · 40-second pitch · storyboard</h1><main>${tiles}</main>`);
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: path.join(DIR, "storyboard.png"), fullPage: true });
  await browser.close(); server.close();

  const probe = JSON.parse(execFileSync("ffprobe", ["-v", "error", "-count_frames", "-show_entries",
    "format=duration:stream=codec_type,width,height,r_frame_rate,duration,nb_read_frames", "-of", "json", opts.out], { encoding: "utf8" }));
  const v = probe.streams.find((s) => s.codec_type === "video"), a = probe.streams.find((s) => s.codec_type === "audio");
  const summary = { width: v.width, height: v.height, fps: v.r_frame_rate, frames: v.nb_read_frames,
    duration: probe.format.duration, vduration: v.duration, aduration: a.duration };
  fs.writeFileSync(path.join(DIR, "timing-report.md"), timingReport(samples, audio, summary, opts));
  console.log(`done in ${((Date.now() - started) / 1000).toFixed(0)} s → ${opts.out}`);
  console.log(JSON.stringify(summary));
}

main().catch((e) => { console.error(e); process.exit(1); });
