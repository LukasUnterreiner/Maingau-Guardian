        if t12:
            cats = Counter(x.get("category") for x in t12)
            refs = [self._ticket_ref(b, x, ["created_at", "category", "status"]) for x in
                    sorted(t12, key=lambda x: x["created_at"], reverse=True)[:8]]
            cat_txt = ", ".join(f"{k} {v}" for k, v in cats.most_common())
