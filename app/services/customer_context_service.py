"""Lighty customer context builder.

Turns the point-in-time ``CustomerState``, the raw dataset rows and the engine
decision into small, typed facts for the employee copilot. The database is the
source of truth: every fact is read from a table or the event stream, or is
computed by the Lighty engine, and carries references to the records it came
from. Nothing here is generated by a language model.

Fact kinds
----------
* ``verified_fact``   read from the dataset or event stream
* ``engine_computed`` derived by the Lighty engine (CLV, churn, eligibility, NBA)
* ``data_gap``        information that is missing in the data or withheld

Data minimisation
-----------------
* Free text (ticket messages, agent notes, call transcripts) is only built for
  roles with the ``free_text`` permission. It is untrusted: it is kept apart from
  the facts, reduced to the customer's own lines, length-limited and scanned
  for instruction-like content.
* Behavioural marketing data (newsletter opens and clicks, portal page views,
  abandoned carts) is only used when profiling consent is effective.
* Birth year, postal code, city and contract ids are never put into fact text.
"""
