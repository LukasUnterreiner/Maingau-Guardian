@dataclass
class CustomerContext:
    customer_id: str
    as_of: datetime
    role: str
    facts: list[Fact]
    refs: dict[str, SourceRef]
    untrusted: list[UntrustedText]
    withheld: list[dict[str, Any]]
    situation: Situation
    decision: Decision
    recommendation: dict[str, Any]
    state: CustomerState
    products: dict[str, dict[str, Any]] = field(repr=False, default_factory=dict)

    def by_key(self, prefix: str) -> list[Fact]:
        return [f for f in self.facts if f.key == prefix or f.key.startswith(prefix + ":")]

    def fact(self, fact_id: str) -> Fact | None:
        return next((f for f in self.facts if f.fact_id == fact_id), None)

    def select(self, topics: set[str] | None, limit: int = 30) -> list[Fact]:
        """Facts relevant to the topics, always including the core facts, in builder order."""
        if not topics:
            return [f for f in self.facts if not f.key.startswith("product_status:")][:limit]
        chosen = [f for f in self.facts
                  if f.key.split(":")[0] in CORE_KEYS or (f.topics & topics)]
        if len(chosen) > limit:
            core = [f for f in chosen if f.key.split(":")[0] in CORE_KEYS]
            rest = [f for f in chosen if f not in core]
            chosen = sorted(core + rest[:max(0, limit - len(core))], key=self.facts.index)
        return chosen

    def refs_for(self, facts: list[Fact]) -> list[SourceRef]:
        seen: list[str] = []
        for f in facts:
            for r in f.ref_ids:
                if r not in seen:
                    seen.append(r)
        return [self.refs[r] for r in seen]


class _Builder:
    def __init__(self) -> None:
        self.facts: list[Fact] = []
        self.refs: dict[str, SourceRef] = {}
        self._ref_index: dict[tuple, str] = {}

    def ref(self, table: str, record_id: Any, fields: list[str] | tuple[str, ...], occurred_at: Any = None,
            note: str | None = None) -> str:
        """One reference per record; fields used by several facts are merged."""
        rid = None if record_id is None else str(record_id)
        key = (table, rid, note) if rid is not None else (table, rid, tuple(fields), note)
        if key in self._ref_index:
            ref = self.refs[self._ref_index[key]]
            ref.fields += [f for f in fields if f not in ref.fields]
            return ref.ref_id
        ref_id = f"R{len(self.refs) + 1}"
        self.refs[ref_id] = SourceRef(ref_id, table, rid, list(fields), _ts(occurred_at), note)
        self._ref_index[key] = ref_id
        return ref_id

    def add(self, key: str, section: str, kind: str, topics: set[str], de: str, en: str, value: Any,
            refs: list[str], sensitivity: str = "standard") -> Fact:
        f = Fact(f"F{len(self.facts) + 1}", key, section, kind, frozenset(topics), de, en, value, refs, sensitivity)
        self.facts.append(f)
        return f


class CustomerContextService:
    def __init__(self, lighty: "Lighty"):
        self.lighty = lighty
        self._churn_sorted: list[float] | None = None

    # ------------------------------------------------------------- helpers
    def _churn_percentile(self, churn: float) -> float:
        """Share of customers whose documented churn (customer_value.churn_prob_12m) is lower."""
        if self._churn_sorted is None:
            self._churn_sorted = sorted(float(v["churn_prob_12m"]) for v in self.lighty.ds.customer_value.values())
        values = self._churn_sorted
        below = sum(1 for v in values if v < churn - 1e-12)
        return below / len(values) if values else 0.0

    def _product_name(self, pid: str | None) -> str:
        if not pid or pid == NO_CONTACT:
            return "No contact"
        return self.lighty.ds.products.get(pid, {}).get("product_name", pid)

    # --------------------------------------------------------------- build
    def build(self, customer_id: str, employee: "Employee") -> CustomerContext:
        """Context at Lighty's default evaluation time (the same state the dashboard shows)."""
        g = self.lighty
        t = g.default_as_of
        s = g.customers.get_state(customer_id, t)
        d = g.engine.decide(customer_id, t, g.settings)
        rec = g.recommend(customer_id)  # same decision id; returns its current approval status
        free_text = employee.can("free_text")
        prof = s.consents[PROFILING_CONSENT]
        b = _Builder()
        withheld: list[dict[str, Any]] = []

        self._customer_information(b, s, d)
        self._customer_experience(b, s, free_text)
        self._marketing(b, s, prof.granted, withheld)
        situation = self._decision_intelligence(b, s, d, rec, free_text, prof.granted)
        self._product_status(b, s, d)
        untrusted = self._untrusted_texts(b, s, t) if free_text else []
        if not free_text:
            n = sum(1 for x in s.tickets if x.get("message_text") or x.get("call_note") or x.get("latest_note"))
            n += len(self._transcripts(s, t))
            if n:
                withheld.append({"category": "free_text", "count": n,
                                 "reason": f"Role '{employee.role}' may not view ticket texts, agent notes or "
                                           "call transcripts."})
        return CustomerContext(customer_id, t, employee.role, b.facts, b.refs, untrusted, withheld, situation, d,
                               rec, s, g.ds.products)

